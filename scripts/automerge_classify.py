#!/usr/bin/env python3
r"""Decide whether a pull request may be merged without a maintainer (D-37, ruling 10(2)).

Run by `.github/workflows/automerge.yml` from the default branch. It never sees the pull
request's checkout or anything its build produced: every input is a response of the
GitHub REST API, saved to a file by the workflow.

Subcommands (exit 0: yes; exit 1: no, with the reasons printed; exit 2: usage error):

  plan    --pr PR.json < FILES
          Check the changed paths only and print the files to fetch, one per line,
          `base <path>` or `head <path>`. Exit 1 if the paths already rule out a merge.
  decide  --run RUN.json --jobs JOBS.json --pr PR.json --branch BRANCH.json
          --compare COMPARE.json --ci-workflow WORKFLOW.json --authors AUTHORS
          --default-branch NAME --base-dir DIR --head-dir DIR < FILES
          The full decision: the CI evidence, the author, and the diff.
  classify --base-dir DIR --head-dir DIR [--title TITLE] < FILES
          The diff classification alone (used by `decide` and by the tests).

FILES is `GET /repos/{o}/{r}/pulls/{n}/files`, as the pages of `gh api --paginate`
(JSON arrays back to back) or one JSON object per value. DIR holds the files of a side at their repository
paths, fetched through `GET /repos/{o}/{r}/contents/{path}?ref=<sha>`.

The diff is accepted only if all of the following hold; anything not understood is a
rejection.
- Every changed path is an existing `.lean` file under `PercLib/` (status modified) other
  than `Basic.lean` and `Defs.lean`, except at most one pure move, with no content change,
  of `tasks/open/<id>.md` or `tasks/claimed/<id>.md` to `tasks/done/<id>.md`, where the
  pull request title begins with `<id>` (the claim convention of ruling 9c).
- The API patch of each Lean file, applied to the fetched base file, gives exactly the
  fetched head file (so the checks below see what the diff says).
- After comments are removed, every changed non-blank line lies inside a `theorem`,
  `lemma` or `example` command (so no definition, structure, instance, notation, import,
  `open`, `variable`, `namespace`, `set_option` ... command is added, removed or edited),
  and contains none of the tokens in FORBIDDEN_TOKENS and no `@[tag` attribute. Lean
  starts a new command at any command keyword, at any column and even in the middle of a
  line, so a changed line may contain no command keyword at all other than `theorem`,
  `lemma`, `example` and their modifiers: FORBIDDEN_TOKENS holds every other keyword that
  can begin a command of the pinned Lean and Mathlib (COMMAND_KEYWORDS, generated by
  scripts/command_keywords.lean). A changed line may also contain no `#` outside string
  and character literals (no `#eval!` and no other `#` command, wherever it starts) and
  no `«…»` identifier. A file containing a string literal with `{` (possibly an
  interpolated string) is rejected, and so is an unterminated comment, string or `«`,
  and a string or character literal with an escape Lean does not accept (see
  STRING_ESCAPE: Lean abandons such a string at the escape and reads the rest as code).
  Lean lexes the longest token, so a `--` or `/-` directly after a symbol (`<--`, `\/-`,
  `//-`) or a character literal directly after a symbol or `''` (`]'"'`) may be code to
  Lean rather than a comment or literal: such a file is rejected too. Identifiers and
  numerals are delimited by Lean's own rules (`isIdFirst`, `isIdRest`, `numberFn`), not
  Python's `isalnum`, and a `'` or `r"` directly after a numeral is rejected. A `'` at a
  token start that fits no character literal is rejected (Lean reports an unterminated
  character literal and resumes lexing two characters later). Where Lean may lex a `'`
  kept as code as a failing character literal, or a numeral after `.` as a number
  rather than a field index, the file is rejected unless both readings open no comment,
  string or character literal before they meet again.
- Auxiliary definitions count as definitions: a `where` clause or a `let rec` inside a
  theorem adds a definition (`z.foo`, `a.f`) to the library, so a changed line matching
  `\bwhere\b` or `\blet\s+rec\b` (after comments are removed) is rejected. Since Lean
  also reads `let` and `rec` on different lines as `let rec`, a change is rejected too
  when its command, with comments removed and literals blanked, matches `\blet\s+rec\b`
  anywhere (a theorem that already holds a `let rec` waits for a maintainer). `rec`
  alone is not a forbidden token: proofs may use `Nat.rec` and other recursors.
- Attribute changes on theorems and lemmas (`@[simp]`, `@[ext]`, ...) are accepted: they
  change how later proofs elaborate but no definition or tagged statement (ruling 9e).
  Attributes that are command keywords or forbidden tokens (`instance`, `tag`,
  `implemented_by`, ...) are rejected by the rule above.
- No `+`/`-` line of the patch carries a `tag` attribute, even inside a comment.
- The statement (everything before the first top-level `:=`) of every tagged declaration
  is the same before and after, and no tag is added or removed.
Standard library only.
"""
